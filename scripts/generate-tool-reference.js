#!/usr/bin/env node
/**
 * Writes docs/TOOLS.md from the tool definitions the server advertises.
 *   node scripts/generate-tool-reference.js          # write
 *   node scripts/generate-tool-reference.js --check  # exit 1 if out of date
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { allToolDefinitions } from '../src/types/index.js';
import { HelpHandlers } from '../src/handlers/helpHandlers.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'docs/TOOLS.md');
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
const byName = new Map(allToolDefinitions.map((t) => [t.name, t]));

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const anchor = (name) => name.replace(/_/g, '_');

function badges(a) {
    const out = [];
    if (a.readOnlyHint) out.push('read-only');
    if (a.destructiveHint) out.push('**destructive**');
    if (a.idempotentHint && !a.readOnlyHint) out.push('idempotent');
    if (a.openWorldHint) out.push('external');
    return out.length ? out.join(' · ') : 'modifies document';
}

function typeOf(s) {
    if (s.enum) return s.enum.map((v) => `\`${v}\``).join(', ');
    if (s.type === 'array') return `array of ${s.items?.type ?? 'any'}`;
    return Array.isArray(s.type) ? s.type.join(' \\| ') : s.type ?? 'any';
}

function toolSection(tool) {
    const props = Object.entries(tool.inputSchema?.properties || {});
    const required = new Set(tool.inputSchema?.required || []);
    let md = `### \`${tool.name}\`\n\n${tool.description}\n\n*${badges(tool.annotations)}*\n\n`;
    if (!props.length) return md + 'No parameters.\n\n';
    md += '| Parameter | Type | Required | Default | Description |\n| --- | --- | --- | --- | --- |\n';
    for (const [k, s] of props) {
        const def = s.default === undefined || s.default === null ? '' : `\`${JSON.stringify(s.default)}\``;
        md += `| \`${k}\` | ${cell(typeOf(s))} | ${required.has(k) ? 'yes' : ''} | ${cell(def)} | ${cell(s.description)} |\n`;
    }
    return md + '\n';
}

function render() {
    const cats = Object.entries(HelpHandlers.toolCategories);
    let md = `# Tool reference\n\n`;
    md += `<!-- Generated by scripts/generate-tool-reference.js from src/types. Do not edit by hand; run \`npm run docs:tools\`. -->\n\n`;
    md += `${allToolDefinitions.length} tools in indesign-mcp-server ${pkg.version}. `;
    md += `Positions and sizes are millimeters from the target page's top-left corner unless a parameter says otherwise; indexes are 0-based. `;
    md += `Labels: *read-only* tools change nothing; **destructive** tools can delete or overwrite work; *idempotent* tools can be repeated safely; *external* tools reach beyond the local InDesign.\n\n`;
    md += `## Contents\n\n`;
    for (const [key, c] of cats) {
        md += `- [${c.name}](#${key}) (${c.tools.length}): ${c.tools.map((n) => `[\`${n}\`](#${anchor(n)})`).join(', ')}\n`;
    }
    md += '\n';
    const seen = new Set();
    for (const [key, c] of cats) {
        md += `## ${c.name}\n<a id="${key}"></a>\n\n${c.description}.\n\n`;
        for (const n of c.tools) {
            if (seen.has(n)) continue;
            seen.add(n);
            md += toolSection(byName.get(n));
        }
    }
    const missing = allToolDefinitions.filter((t) => !seen.has(t.name));
    if (missing.length) throw new Error(`tools not in any help category: ${missing.map((t) => t.name).join(', ')}`);
    return md;
}

const md = render();
if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== md) {
        console.error('docs/TOOLS.md is out of date: run npm run docs:tools');
        process.exitCode = 1;
    } else {
        console.log('docs/TOOLS.md is up to date');
    }
} else {
    writeFileSync(target, md);
    console.log(`wrote docs/TOOLS.md (${allToolDefinitions.length} tools)`);
}
